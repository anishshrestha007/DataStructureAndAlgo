#!/usr/bin/env node
// Rebuilds playground/manifest.js, the list of files the playground sidebar shows.
// Run it after adding, moving or renaming practice files:
//
//   node playground/generate-manifest.js
//
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(__dirname, "manifest.js");

const SECTIONS = [
  { dir: "dsa", label: "Data Structures & Algorithms" },
  { dir: "javascript", label: "JavaScript Concepts" },
  { dir: "courses", label: "Courses" },
  { dir: "scratch", label: "Scratch" },
];

const ACRONYMS = { dom: "DOM", oop: "OOP", dsa: "DSA", js: "JS" };

function pretty(slug) {
  return slug
    .split("-")
    .map((w) => (w === "and" ? "&" : ACRONYMS[w] || w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.name.endsWith(".js")) out.push(full);
  }
  return out;
}

function stripComments(code) {
  return code.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
}

const LOOKS_LIKE_CODE = new RegExp(
  [
    /[;{}]\s*$/, // statement or block endings
    /^\s*(function|var|let|const|return|if|for|while|class|console\.)\b/,
    /=>|===|!==|\|\||&&/,
    /^\s*[\])}]/,
    /\w\[[^\]]*\]\s*[<>]/, // comparisons like nums[i] > nums[j]
    /^Driver program/i,
    /^\s*\.\w|^[\w$.]+\(.*\);?\s*$/, // method chains and bare calls
    /^\s*\/\*/, // commented-out block comment
    /^\s*[\w$.[\]]+\s*=[^=]/, // assignment
    /^\s*[\w$]+\s*:\s*["'\d{[]/, // object literal entry
  ]
    .map((r) => r.source)
    .join("|")
);
const SKIP_LINE = /^(Reference( URL)?\s*:|https?:\/\/)/i;
const STOP_LINE = /^(Example\s*\d*\s*:|Input\s*:|Output\s*:|Explanation\s*:|Definition for)/i;

// Uses the comment block at the top of the file, skipping commented-out code.
function summarize(code) {
  const lines = code.split(/\r?\n/);
  const text = [];
  let inBlock = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (!inBlock && line === "") {
      if (text.length) break;
      continue;
    }
    if (!inBlock && line.startsWith("/*")) inBlock = true;
    const isComment = inBlock || line.startsWith("//");
    if (!isComment) break;
    let body = line
      .replace(/^\/\*+\s?/, "")
      .replace(/\*+\/$/, "")
      .replace(/^(\/\/+\s?)+/, "")
      .replace(/^\*\s?/, "")
      .trim();
    if (inBlock && line.endsWith("*/")) inBlock = false;
    if (STOP_LINE.test(body)) {
      if (text.length) break;
      continue;
    }
    if (!body || body.startsWith("@") || SKIP_LINE.test(body) || LOOKS_LIKE_CODE.test(body)) continue;
    text.push(body);
    if (text.join(" ").length > 260) break;
  }
  const s = text.join(" ").replace(/\s+/g, " ").trim();
  return s.length > 280 ? s.slice(0, 277).trimEnd() + "…" : s;
}

function kindsOf(code) {
  const c = stripComments(code);
  const kinds = [];
  if (/\bself\.addEventListener\(\s*["']message/.test(c)) kinds.push("worker");
  if (/^\s*(import\s|export\s)/m.test(c)) kinds.push("module");
  if (/\brequire\(|module\.exports/.test(c)) kinds.push("node");
  if (/\bdocument\.|\bwindow\.|\balert\(/.test(c)) kinds.push("dom");
  return kinds;
}

const files = [];
for (const section of SECTIONS) {
  const base = path.join(ROOT, section.dir);
  if (!fs.existsSync(base)) continue;
  for (const full of walk(base)) {
    const rel = path.relative(ROOT, full).split(path.sep).join("/");
    const parts = rel.split("/").slice(1, -1); // folders inside the section
    const code = fs.readFileSync(full, "utf8");
    files.push({
      path: rel,
      name: path.basename(rel, ".js"),
      section: section.label,
      group: parts.length ? parts.map(pretty).join(" / ") : "General",
      lines: code.split(/\r?\n/).length,
      kinds: kindsOf(code),
      summary: section.dir === "scratch" ? "" : summarize(code),
    });
  }
}

files.sort(
  (a, b) =>
    SECTIONS.findIndex((s) => s.label === a.section) - SECTIONS.findIndex((s) => s.label === b.section) ||
    a.group.localeCompare(b.group) ||
    a.name.localeCompare(b.name, undefined, { sensitivity: "base" })
);

const body =
  "// Generated by playground/generate-manifest.js. Do not edit by hand.\n" +
  "// Regenerate with: node playground/generate-manifest.js\n" +
  "window.PLAYGROUND_FILES = [\n" +
  files.map((f) => "  " + JSON.stringify(f)).join(",\n") +
  "\n];\n";

fs.writeFileSync(OUT, body);
console.log(`Wrote ${files.length} files to ${path.relative(ROOT, OUT)}`);
